"""Behavior of the pre-push guard that binds hook evidence to the push."""

from __future__ import annotations

import os
from pathlib import Path

import pytest

from scripts.check_push_snapshot import (
    VALIDATOR_MARKER,
    VALIDATOR_SOURCE,
    ValidatorError,
    install_validator,
    pushed_revision,
    selected_update,
    snapshot_mismatches,
    validator_problem,
    validator_script,
)
from scripts.git_snapshot import git_path
from scripts.process_runner import ProcessResult, run_process
from tests.support.git_repository import initialize_git_repository, run_git

REPOSITORY_ROOT = Path(__file__).parents[2]
PUSH_SNAPSHOT = REPOSITORY_ROOT / 'scripts' / 'check_push_snapshot.py'
ZERO = '0' * 40

pytestmark = pytest.mark.unit


def _committed_repository(repo: Path) -> str:
    """Create a repository with one commit and return its HEAD commit."""
    initialize_git_repository(repo)
    (repo / 'module.py').write_text('VALUE = 1\n', encoding='utf-8')
    (repo / '.gitignore').write_text(
        'ignored.log\n__pycache__/\nlocal_settings.py\nmypy.ini\n',
        encoding='utf-8',
    )
    run_git(repo, 'add', '--', 'module.py', '.gitignore')
    run_git(repo, 'commit', '--quiet', '-m', 'baseline')
    return run_git(repo, 'rev-parse', 'HEAD').stdout.strip()


def _commit_on_branch(repo: Path, branch: str) -> str:
    """Commit a change on a new branch, return to the previous one."""
    run_git(repo, 'switch', '--quiet', '-c', branch)
    (repo / 'module.py').write_text('VALUE = 2\n', encoding='utf-8')
    run_git(repo, 'commit', '--quiet', '-am', f'{branch} change')
    commit = run_git(repo, 'rev-parse', 'HEAD').stdout.strip()
    run_git(repo, 'switch', '--quiet', '-')
    return commit


def _install(repo: Path) -> Path:
    """Install the validator next to a stand-in pre-commit hook."""
    hook = git_path('hooks/pre-push', repo)
    hook.parent.mkdir(parents=True, exist_ok=True)
    hook.write_text('# File generated by pre-commit\n', encoding='utf-8')
    return install_validator(repo)


def _push_environment(pushed: str) -> dict[str, str]:
    """Return the variables pre-commit exports while a push runs."""
    return {
        'PRE_COMMIT_REMOTE_NAME': 'origin',
        'PRE_COMMIT_REMOTE_URL': 'https://example.invalid/repo.git',
        'PRE_COMMIT_LOCAL_BRANCH': 'refs/heads/main',
        'PRE_COMMIT_REMOTE_BRANCH': 'refs/heads/main',
        'PRE_COMMIT_FROM_REF': ZERO,
        'PRE_COMMIT_TO_REF': pushed,
    }


def _validate(
    repo: Path, *updates: tuple[str, str, str, str]
) -> ProcessResult:
    """Run the validator on ref updates as Git passes them to the hook."""
    listing = repo.parent / f'{repo.name}-updates.txt'
    listing.write_text(
        ''.join(' '.join(update) + '\n' for update in updates),
        encoding='utf-8',
    )
    return run_process(
        [
            'sh',
            '-c',
            'exec sh "$0" origin https://example.invalid/repo.git < "$1"',
            str(VALIDATOR_SOURCE),
            str(listing),
        ],
        cwd=repo,
        check=False,
    )


def _run_guard(repo: Path, **push_environment: str) -> ProcessResult:
    """Execute the guard with the variables pre-commit exports on push."""
    environment = {
        key: value
        for key, value in os.environ.items()
        if not key.startswith('PRE_COMMIT')
    }
    environment.update(push_environment)
    return run_process(
        ['python', str(PUSH_SNAPSHOT)], cwd=repo, env=environment, check=False
    )


@pytest.mark.parametrize(
    ('environment', 'expected'),
    [
        ({'PRE_COMMIT_TO_REF': 'abc'}, 'abc'),
        ({'PRE_COMMIT_TO_REF': '  '}, None),
        ({'PRE_COMMIT_LOCAL_BRANCH': 'refs/heads/main'}, None),
        ({}, None),
    ],
)
def test_manual_runs_name_their_commit_explicitly(
    environment: dict[str, str], expected: str | None
) -> None:
    """Outside a push, only an explicit --to-ref selects a commit."""
    assert pushed_revision(environment) == expected


def test_guard_skips_outside_a_push(tmp_path: Path) -> None:
    """Manual stage runs keep working and declare their coverage."""
    _committed_repository(tmp_path)

    result = _run_guard(tmp_path)

    assert result.returncode == 0
    assert 'SKIP [PUSH_SNAPSHOT]' in result.stdout


def test_a_manual_run_of_a_clean_checkout_passes(tmp_path: Path) -> None:
    """Logs and bytecode caches are not snapshot contamination."""
    head = _committed_repository(tmp_path)
    (tmp_path / 'ignored.log').write_text('local log\n', encoding='utf-8')
    cache = tmp_path / 'src' / '__pycache__'
    cache.mkdir(parents=True)
    (cache / 'module.cpython-313.pyc').write_bytes(b'\0')

    result = _run_guard(tmp_path, PRE_COMMIT_TO_REF=head)

    assert result.returncode == 0, result.stderr
    assert 'PASS [PUSH_SNAPSHOT]' in result.stdout


def test_a_manual_run_rejects_a_commit_other_than_head(tmp_path: Path) -> None:
    """The hooks would otherwise validate a different commit."""
    _committed_repository(tmp_path)
    feature = _commit_on_branch(tmp_path, 'feature')

    result = _run_guard(tmp_path, PRE_COMMIT_TO_REF=feature)

    assert result.returncode == 1
    assert 'is not the checked-out HEAD' in result.stderr


def _contaminate(repo: Path, contamination: str) -> None:
    """Make the checkout differ from HEAD in one specific way."""
    module = repo / 'module.py'
    if contamination == 'untracked':
        (repo / 'helper.py').write_text('HELPER = 1\n', encoding='utf-8')
    elif contamination == 'ignored-source':
        target = repo / 'src' / 'pkg' / 'local_settings.py'
        target.parent.mkdir(parents=True)
        target.write_text('TOKEN = 1\n', encoding='utf-8')
    elif contamination == 'ignored-configuration':
        (repo / 'mypy.ini').write_text('[mypy]\n', encoding='utf-8')
    else:
        flag = {
            'assume-unchanged': '--assume-unchanged',
            'skip-worktree': '--skip-worktree',
        }.get(contamination)
        if flag is not None:
            run_git(repo, 'update-index', flag, '--', 'module.py')
        module.write_text('VALUE = 3\n', encoding='utf-8')
        if contamination == 'staged':
            run_git(repo, 'add', '--', 'module.py')


@pytest.mark.parametrize(
    ('contamination', 'label'),
    [
        ('staged', 'staged changes'),
        ('unstaged', 'unstaged changes'),
        ('untracked', 'untracked files'),
        ('assume-unchanged', 'assume-unchanged or skip-worktree edits'),
        ('skip-worktree', 'assume-unchanged or skip-worktree edits'),
        ('ignored-source', 'ignored source or tool files'),
        ('ignored-configuration', 'ignored source or tool files'),
    ],
)
def test_guard_rejects_inputs_that_are_not_in_the_pushed_commit(
    tmp_path: Path, contamination: str, label: str
) -> None:
    """Anything the hooks could read beyond HEAD would skew the evidence."""
    head = _committed_repository(tmp_path)
    _contaminate(tmp_path, contamination)

    mismatches = snapshot_mismatches(head, tmp_path)

    assert len(mismatches) == 1, mismatches
    assert mismatches[0].startswith(label)


def test_an_unchanged_flagged_file_is_not_a_mismatch(tmp_path: Path) -> None:
    """An index flag alone does not change what the hooks read."""
    head = _committed_repository(tmp_path)
    run_git(tmp_path, 'update-index', '--assume-unchanged', '--', 'module.py')

    assert snapshot_mismatches(head, tmp_path) == []


def test_guard_fails_closed_for_an_unknown_revision(tmp_path: Path) -> None:
    """A revision Git cannot resolve is infrastructure, not approval."""
    _committed_repository(tmp_path)

    result = _run_guard(tmp_path, PRE_COMMIT_TO_REF='missing-revision')

    assert result.returncode == 2
    assert 'ERROR [PUSH_SNAPSHOT]' in result.stderr


def test_the_selected_update_comes_from_the_push_environment() -> None:
    """pre-commit names one update; its fields come from the environment."""
    update = selected_update(_push_environment('b' * 40))

    assert update is not None
    assert update.local_object == 'b' * 40
    assert update.remote_ref == 'refs/heads/main'
    assert not update.deletes
    assert selected_update({'PRE_COMMIT_REMOTE_NAME': 'origin'}) is None


def test_a_root_push_is_checked_through_its_local_ref(tmp_path: Path) -> None:
    """Publishing a root commit names no range, only the local ref."""
    _committed_repository(tmp_path)
    _commit_on_branch(tmp_path, 'other')
    _install(tmp_path)
    environment = _push_environment('')
    environment['PRE_COMMIT_LOCAL_BRANCH'] = 'refs/heads/other'
    del environment['PRE_COMMIT_FROM_REF']

    result = _run_guard(tmp_path, **environment)

    assert result.returncode == 1
    assert 'refs/heads/other -> refs/heads/main publishes' in result.stderr


def test_install_writes_an_executable_validator(tmp_path: Path) -> None:
    """The validator is pre-commit's migration-mode pre-push hook."""
    _committed_repository(tmp_path)
    assert validator_problem(tmp_path) is not None

    hook = _install(tmp_path)
    install_validator(tmp_path)

    assert hook == git_path('hooks/pre-push.legacy', tmp_path)
    assert hook.read_text(encoding='utf-8') == validator_script()
    assert validator_script().splitlines()[1] == VALIDATOR_MARKER
    assert validator_problem(tmp_path) is None


def test_install_requires_the_pre_commit_hook(tmp_path: Path) -> None:
    """Without pre-commit's hook, nothing would run the validator."""
    _committed_repository(tmp_path)

    with pytest.raises(ValidatorError, match='pre-commit install'):
        install_validator(tmp_path)


def test_install_never_overwrites_another_legacy_hook(tmp_path: Path) -> None:
    """A user's migrated hook is merged by hand, not replaced."""
    _committed_repository(tmp_path)
    legacy = git_path('hooks/pre-push.legacy', tmp_path)
    legacy.parent.mkdir(parents=True, exist_ok=True)
    legacy.write_text('#!/bin/sh\nexit 0\n', encoding='utf-8')

    with pytest.raises(ValidatorError):
        _install(tmp_path)
    assert legacy.read_text(encoding='utf-8') == '#!/bin/sh\nexit 0\n'
    assert 'replaced by another hook' in str(validator_problem(tmp_path))


def test_install_upgrades_an_earlier_validator(tmp_path: Path) -> None:
    """A hook this script installed before is replaced by the current one."""
    _committed_repository(tmp_path)
    legacy = git_path('hooks/pre-push.legacy', tmp_path)
    legacy.parent.mkdir(parents=True, exist_ok=True)
    legacy.write_text(
        f'#!/bin/sh\n{VALIDATOR_MARKER} Earlier version.\ncat > /dev/null\n',
        encoding='utf-8',
    )
    assert 'outdated' in str(validator_problem(tmp_path))

    _install(tmp_path)

    assert legacy.read_text(encoding='utf-8') == validator_script()
    assert validator_problem(tmp_path) is None


def test_a_validator_that_cannot_run_is_reported(tmp_path: Path) -> None:
    """pre-commit skips a legacy hook that is not executable."""
    _committed_repository(tmp_path)
    _install(tmp_path).chmod(0o644)

    assert 'not executable' in str(validator_problem(tmp_path))


def test_a_push_without_the_validator_fails(tmp_path: Path) -> None:
    """Without the validator, updates beyond the first go unchecked."""
    head = _committed_repository(tmp_path)

    result = _run_guard(tmp_path, **_push_environment(head))

    assert result.returncode == 1
    assert 'validator is missing' in result.stderr
    assert 'check_push_snapshot.py --install' in result.stderr


@pytest.mark.parametrize(
    ('published', 'expected'), [(False, 1), (True, 0)], ids=['new', 'known']
)
def test_the_first_update_is_checked_before_the_hooks(
    tmp_path: Path, published: bool, expected: int
) -> None:
    """A first update with new commits other than HEAD fails fast."""
    _committed_repository(tmp_path)
    other = _commit_on_branch(tmp_path, 'other')
    if published:
        run_git(tmp_path, 'update-ref', 'refs/remotes/origin/other', other)
    _install(tmp_path)

    result = _run_guard(tmp_path, **_push_environment(other))

    assert result.returncode == expected, result.stderr
    assert ('publishes' in result.stderr) is not published


def test_a_clean_push_of_head_passes(tmp_path: Path) -> None:
    """The guard accepts a clean checkout pushed with its validator."""
    head = _committed_repository(tmp_path)
    _install(tmp_path)

    result = _run_guard(tmp_path, **_push_environment(head))

    assert result.returncode == 0, result.stderr
    assert 'PASS [PUSH_SNAPSHOT]' in result.stdout


def test_the_validator_rejects_every_ref_with_other_commits(
    tmp_path: Path,
) -> None:
    """A second ref with unpublished commits fails the whole push."""
    head = _committed_repository(tmp_path)
    other = _commit_on_branch(tmp_path, 'other')

    result = _validate(
        tmp_path,
        ('refs/heads/main', head, 'refs/heads/aaa', ZERO),
        ('refs/heads/other', other, 'refs/heads/zzz', ZERO),
    )

    assert result.returncode == 1
    assert 'refs/heads/other -> refs/heads/zzz publishes' in result.stderr
    assert 'refs/heads/aaa' not in result.stderr


def test_the_validator_allows_updates_without_new_commits(
    tmp_path: Path,
) -> None:
    """Deletions, repeated HEADs, tags, and published commits add nothing."""
    head = _committed_repository(tmp_path)
    other = _commit_on_branch(tmp_path, 'other')
    run_git(tmp_path, 'update-ref', 'refs/remotes/origin/other', other)
    run_git(tmp_path, 'tag', '--annotate', '--message', 'release', 'v1')
    tag = run_git(tmp_path, 'rev-parse', 'v1').stdout.strip()

    result = _validate(
        tmp_path,
        ('refs/heads/main', head, 'refs/heads/aaa', ZERO),
        ('refs/heads/main', head, 'refs/heads/bbb', ZERO),
        ('(delete)', ZERO, 'refs/heads/old', head),
        ('refs/heads/other', other, 'refs/heads/mirror', ZERO),
        ('refs/tags/v1', tag, 'refs/tags/v1', ZERO),
    )

    assert result.returncode == 0, result.stderr
    assert result.stderr == ''


def test_the_validator_accepts_a_ref_the_remote_already_has(
    tmp_path: Path,
) -> None:
    """Pushing a commit back to a remote ref that holds it adds nothing."""
    _committed_repository(tmp_path)
    other = _commit_on_branch(tmp_path, 'other')

    result = _validate(
        tmp_path, ('refs/heads/other', other, 'refs/heads/other', other)
    )

    assert result.returncode == 0, result.stderr


@pytest.mark.parametrize(
    ('update', 'expected', 'message'),
    [
        (
            ('HEAD', 'f' * 40, 'refs/heads/x', ZERO),
            1,
            'does not push a commit',
        ),
        (('HEAD', 'not-an-object', 'refs/heads/x', ZERO), 2, 'malformed'),
        (('refs/heads/x', ZERO, ZERO), 2, 'malformed'),
    ],
    ids=['unknown-object', 'non-hex-object', 'missing-field'],
)
def test_the_validator_fails_closed_on_unusable_updates(
    tmp_path: Path,
    update: tuple[str, str, str, str],
    expected: int,
    message: str,
) -> None:
    """An update the validator cannot verify is never approved."""
    _committed_repository(tmp_path)

    result = _validate(tmp_path, update)

    assert result.returncode == expected
    assert message in result.stderr
