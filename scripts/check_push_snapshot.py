#!/usr/bin/env python3
"""Reject pre-push evidence that would not describe the pushed commits.

Pre-push hooks run against the checkout, not against the pushed objects, and
pre-commit hands them only the first ref of a push. Two parts close both gaps:

* ``--install`` adds a validator as pre-commit's migration-mode hook
  (``pre-push.legacy``). pre-commit runs it before its own hooks, passes it
  Git's complete list of ref updates, and fails the push when it fails. It
  rejects every update that publishes commits missing from the local
  remote-tracking refs unless the update pushes the checked-out HEAD; stale
  tracking refs hide commits the remote no longer has. It reads only its own
  input and stores nothing, so concurrent pushes cannot exchange their ref
  lists.
* As pre-commit's first pre-push hook, this gate requires that validator,
  rejects a first update other than HEAD before the expensive hooks run, and
  requires the checkout to be exactly HEAD: no staged, unstaged, or untracked
  change, no tracked file hidden by ``assume-unchanged`` or ``skip-worktree``,
  and no ignored source or tool configuration that the tests or type checkers
  could load. pre-commit stashes unstaged tracked edits before an incremental
  push, so they reach this gate only when the push includes a root commit.

When the validator rejects a later update, pre-commit still runs its hooks
before Git rejects the push. The gate is read-only: it never stashes, checks
out, or removes anything.

Fail-closed: exits 2 on Git errors, 1 on a mismatch or a missing validator,
and 0 when the snapshot matches or when no push context exists, such as a
manual pre-commit run.
"""

from __future__ import annotations

import argparse
import os
import sys
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path

if __package__ in {None, ''}:
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from scripts.git_changes import GitInspectionError, resolve_commit
from scripts.git_snapshot import (
    commit_exists,
    git_path,
    has_commits_outside,
    hidden_index_changes,
    ignored_paths,
    staged_paths_against_head,
    unstaged_paths,
    untracked_paths,
)

LISTED_PATH_LIMIT = 10
ZERO_OBJECT = '0' * 40
VALIDATOR_HOOK = 'hooks/pre-push.legacy'
PRE_COMMIT_HOOK = 'hooks/pre-push'
PRE_COMMIT_MARKER = 'File generated by pre-commit'
VALIDATOR_MARKER = '# Installed by scripts/check_push_snapshot.py --install.'
INSTALL_COMMAND = (
    'uv run --locked --no-sync python scripts/check_push_snapshot.py --install'
)
VALIDATOR_SOURCE = Path(__file__).resolve().with_name('push_ref_validator.sh')
SOURCE_ROOTS = ('src', 'tests', 'scripts', 'examples', '.agents/scripts')
IMPORTABLE_SUFFIXES = ('.py', '.pyi', '.pyw', '.pyc', '.pyd', '.so')
TOOL_CONFIGURATIONS = frozenset(
    {
        '.coveragerc',
        '.importlinter',
        '.mypy.ini',
        '.pytest.ini',
        '.ruff.toml',
        'mypy.ini',
        'pyproject.toml',
        'pytest.ini',
        'ruff.toml',
        'setup.cfg',
        'tox.ini',
    }
)


@dataclass(frozen=True)
class RefUpdate:
    """One line of the list Git passes to pre-push hooks."""

    local_ref: str
    local_object: str
    remote_ref: str
    remote_object: str

    @property
    def deletes(self) -> bool:
        """Return whether the update deletes the remote ref."""
        return set(self.local_object) == {'0'}


class ValidatorError(RuntimeError):
    """Raised when the ref-update validator cannot be read or installed."""


def validator_script() -> str:
    """Return the validator that ``--install`` copies into the hooks.

    Raises:
        ValidatorError: If the tracked validator cannot be read.
    """
    try:
        return VALIDATOR_SOURCE.read_text(encoding='utf-8')
    except (OSError, UnicodeError) as error:
        raise ValidatorError(
            f'cannot read {VALIDATOR_SOURCE}: {error}'
        ) from error


def pushed_revision(environment: Mapping[str, str]) -> str | None:
    """Return the commit that a manual pre-push run names, if any."""
    revision = environment.get('PRE_COMMIT_TO_REF', '').strip()
    return revision or None


def selected_update(environment: Mapping[str, str]) -> RefUpdate | None:
    """Return the update pre-commit selected for its hooks, if it names one.

    A push that publishes a root commit names no commit range, only the local
    ref, which then stands for the pushed object.
    """
    local_ref = environment.get('PRE_COMMIT_LOCAL_BRANCH', '').strip()
    revision = pushed_revision(environment) or local_ref
    if not revision:
        return None
    return RefUpdate(
        local_ref or revision,
        revision,
        environment.get('PRE_COMMIT_REMOTE_BRANCH', '').strip() or 'remote',
        environment.get('PRE_COMMIT_FROM_REF', '').strip() or ZERO_OBJECT,
    )


def _listed(paths: list[str]) -> str:
    """Render a bounded, deterministic list of repository paths."""
    shown = ', '.join(paths[:LISTED_PATH_LIMIT])
    hidden = len(paths) - LISTED_PATH_LIMIT
    return f'{shown} (+{hidden} more)' if hidden > 0 else shown


def _loadable(path: str) -> bool:
    """Return whether tests or type checkers may load an ignored file."""
    name = path.rsplit('/', maxsplit=1)[-1]
    if name in TOOL_CONFIGURATIONS:
        return True
    if not name.endswith(IMPORTABLE_SUFFIXES):
        return False
    return not (name.endswith('.pyc') and '__pycache__/' in path)


def ignored_inputs(repo_root: Path | None = None) -> list[str]:
    """Return ignored files that could change what the hooks observe.

    Tool caches and ``__pycache__`` bytecode stay allowed; Python only loads
    such bytecode next to its tracked source.
    """
    top_level = [
        path
        for path in ignored_paths(['.'], repo_root, collapse_directories=True)
        if '/' not in path
    ]
    nested = ignored_paths(list(SOURCE_ROOTS), repo_root)
    return sorted(path for path in {*top_level, *nested} if _loadable(path))


def checkout_mismatches(repo_root: Path | None = None) -> list[str]:
    """Return every input of the checkout that HEAD does not contain."""
    mismatches: list[str] = []
    for label, paths in (
        ('staged changes', staged_paths_against_head(repo_root)),
        ('unstaged changes', unstaged_paths(repo_root)),
        ('untracked files', untracked_paths(repo_root)),
        (
            'assume-unchanged or skip-worktree edits',
            hidden_index_changes(repo_root),
        ),
        ('ignored source or tool files', ignored_inputs(repo_root)),
    ):
        if paths:
            mismatches.append(
                f'{label} are not part of the pushed commit: {_listed(paths)}'
            )
    return mismatches


def snapshot_mismatches(
    revision: str, repo_root: Path | None = None
) -> list[str]:
    """Return every reason why the checkout is not the given commit."""
    mismatches: list[str] = []
    pushed = resolve_commit(revision, repo_root)
    head = resolve_commit('HEAD', repo_root)
    if pushed != head:
        mismatches.append(
            f'pushed commit {pushed[:12]} is not the checked-out HEAD '
            f'{head[:12]}; switch to the pushed branch before pushing'
        )
    return mismatches + checkout_mismatches(repo_root)


def validator_problem(repo_root: Path | None = None) -> str | None:
    """Describe why the installed validator cannot be trusted, if it cannot."""
    hook = git_path(VALIDATOR_HOOK, repo_root)
    try:
        installed = hook.read_text(encoding='utf-8', errors='replace')
    except FileNotFoundError:
        return f'missing at {hook}'
    except OSError as error:
        return f'unreadable at {hook} ({error})'
    if installed != validator_script():
        if VALIDATOR_MARKER in installed:
            return f'outdated at {hook}'
        return f'replaced by another hook at {hook}'
    if os.name != 'nt' and not os.access(hook, os.X_OK):
        return f'not executable at {hook}'
    return None


def update_mismatches(
    updates: Sequence[RefUpdate],
    remote: str,
    repo_root: Path | None = None,
) -> list[str]:
    """Return the updates that publish commits other than the checkout."""
    head = resolve_commit('HEAD', repo_root)
    mismatches: list[str] = []
    for update in updates:
        if update.deletes:
            continue
        target = f'{update.local_ref} -> {update.remote_ref}'
        if not commit_exists(update.local_object, repo_root):
            mismatches.append(f'{target} does not push a commit')
            continue
        commit = resolve_commit(update.local_object, repo_root)
        if commit == head:
            continue
        excluded = (
            [update.remote_object]
            if commit_exists(update.remote_object, repo_root)
            else []
        )
        if has_commits_outside(commit, excluded, remote, repo_root):
            mismatches.append(
                f'{target} publishes {commit[:12]}, not the checked-out HEAD '
                f'{head[:12]}; push each ref from its own clean checkout'
            )
    return mismatches


def push_mismatches(
    environment: Mapping[str, str], repo_root: Path | None = None
) -> list[str]:
    """Return every reason why the hooks would not validate this push."""
    mismatches: list[str] = []
    problem = validator_problem(repo_root)
    if problem is not None:
        mismatches.append(
            f'the ref-update validator is {problem}, so updates beyond the '
            f'first would go unchecked; install it with: {INSTALL_COMMAND}'
        )
    update = selected_update(environment)
    if update is not None:
        remote = environment.get('PRE_COMMIT_REMOTE_NAME', '').strip()
        mismatches.extend(update_mismatches([update], remote, repo_root))
    return mismatches + checkout_mismatches(repo_root)


def install_validator(repo_root: Path | None = None) -> Path:
    """Install the validator as pre-commit's migration-mode pre-push hook.

    An earlier version of the validator is replaced; any other hook is kept.

    Raises:
        ValidatorError: If pre-commit's hook is absent or another legacy hook
            would be overwritten.
    """
    pre_push = git_path(PRE_COMMIT_HOOK, repo_root)
    hook = git_path(VALIDATOR_HOOK, repo_root)
    try:
        installed_by_pre_commit = pre_push.is_file() and (
            PRE_COMMIT_MARKER
            in pre_push.read_text(encoding='utf-8', errors='replace')
        )
        if not installed_by_pre_commit:
            raise ValidatorError(
                f'{pre_push} is not the pre-commit hook; run '
                '`uv run --locked --no-sync pre-commit install '
                '--install-hooks` first'
            )
        if hook.is_symlink() or (
            hook.exists()
            and VALIDATOR_MARKER
            not in hook.read_text(encoding='utf-8', errors='replace')
        ):
            raise ValidatorError(
                f'{hook} already holds another hook; merge it by hand'
            )
        hook.write_text(validator_script(), encoding='utf-8', newline='\n')
        hook.chmod(0o755)
    except OSError as error:
        raise ValidatorError(f'cannot install {hook}: {error}') from error
    return hook


def _report(mismatches: list[str]) -> int:
    """Print the verdict for a push and return its exit status."""
    if not mismatches:
        sys.stdout.write(
            'PASS [PUSH_SNAPSHOT]: the checkout is exactly the pushed HEAD.\n'
        )
        return 0
    sys.stderr.write(
        'FAIL [PUSH_SNAPSHOT]: pre-push checks would not validate what '
        'this push publishes:\n'
    )
    for mismatch in mismatches:
        sys.stderr.write(f'  • {mismatch}\n')
    sys.stderr.write(
        '\nResolution: push one commit at a time from a clean checkout of it '
        '(commit, stash, or remove the listed paths), then push again.\n'
    )
    return 1


def main(argv: Sequence[str] | None = None) -> int:
    """Install the validator or check the current push."""
    parser = argparse.ArgumentParser(
        description='Validate that a push publishes only the clean checkout.'
    )
    parser.add_argument(
        '--install',
        action='store_true',
        help='Install the ref-update validator next to the pre-commit hook.',
    )
    arguments = parser.parse_args(argv)
    try:
        if arguments.install:
            hook = install_validator()
            sys.stdout.write(f'PASS [PUSH_SNAPSHOT]: validator at {hook}\n')
            return 0
        if os.environ.get('PRE_COMMIT_REMOTE_NAME', '').strip():
            return _report(push_mismatches(os.environ))
        revision = pushed_revision(os.environ)
        if revision is None:
            sys.stdout.write(
                'SKIP [PUSH_SNAPSHOT]: not invoked by git push; results cover '
                'the working tree.\n'
            )
            return 0
        return _report(snapshot_mismatches(revision))
    except ValidatorError as err:
        sys.stderr.write(f'ERROR [PUSH_SNAPSHOT]: {err}\n')
        return 2
    except (GitInspectionError, ValueError) as err:
        sys.stderr.write(
            f'ERROR [PUSH_SNAPSHOT]: unable to inspect the push: {err}\n'
        )
        return 2


if __name__ == '__main__':
    sys.exit(main())
